type_kt.append("@Immutable")
type_kt.append("data class VoidwireCodeTypography(")
ext_t = [(r, t) for r, t in T["typography"].items() if t.get("extended")]
for role, t in ext_t:
    type_kt.append(f"    val {role}: TextStyle = {style(t)},")
type_kt.append(")")
type_kt.append("")
type_kt.append("val LocalVoidwireCodeTypography = staticCompositionLocalOf { VoidwireCodeTypography() }")
