def style(t):
    return (f"TextStyle(fontFamily = {famname[t['family']]}, fontWeight = FontWeight.{weights[t['weight']]}, "
            f"fontSize = {t['size']}.sp, lineHeight = {t['lineHeight']}.sp, letterSpacing = {t['tracking']}.em)")

type_kt.append("val VoidwireTypography = Typography(")
for role, t in T["typography"].items():
    if not t.get("extended"):
        type_kt.append(f"    {role} = {style(t)},")
type_kt.append(")")
type_kt.append("")
