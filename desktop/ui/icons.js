function vwIcon(name, cls) {
  const s = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  s.setAttribute("viewBox", "0 0 24 24");
  s.setAttribute("class", "i" + (cls ? " " + cls : ""));
  s.setAttribute("aria-hidden", "true");
  const tpl = document.createElementNS("http://www.w3.org/2000/svg", "g");
  tpl.innerHTML = VW_ICONS[name] || ""; // constant strings only
  while (tpl.firstChild) s.appendChild(tpl.firstChild);
  return s;
}
function vwIcons(root) {
  for (const el of (root || document).querySelectorAll("i[data-i]")) el.replaceWith(vwIcon(el.dataset.i, el.className));
}
