#!/usr/bin/env python3
"""Convert the brand's flat SVGs (path + fill + translate/scale only) into
Android VectorDrawables. M1.1: the top-bar lockup and the share-dialog mark
(brand/voidwire/ui/SPEC.md 1.5). Usage: svg2vd.py in.svg out.xml"""
import re, sys, xml.etree.ElementTree as ET

NS = "{http://www.w3.org/2000/svg}"


def transforms(t):
    out = []
    for name, args in re.findall(r"(translate|scale)\(([^)]*)\)", t or ""):
        v = [float(x) for x in re.split(r"[ ,]+", args.strip())]
        if name == "translate":
            out.append(f'<group android:translateX="{v[0]}" android:translateY="{v[1] if len(v) > 1 else 0}">')
        else:
            out.append(f'<group android:scaleX="{v[0]}" android:scaleY="{v[1] if len(v) > 1 else v[0]}">')
    return out


def walk(el, lines):
    for c in el:
        tag = c.tag.replace(NS, "")
        opens = transforms(c.get("transform"))
        lines += opens
        if tag == "g":
            walk(c, lines)
        elif tag == "path":
            fill = c.get("fill", "#000000")
            ft = ' android:fillType="evenOdd"' if c.get("fill-rule") == "evenodd" else ""
            lines.append(f'<path android:fillColor="{fill}"{ft} android:pathData="{c.get("d")}"/>')
        else:
            sys.exit(f"unsupported element {tag}")
        lines += ["</group>"] * len(opens)


def main():
    src, out = sys.argv[1], sys.argv[2]
    root = ET.parse(src).getroot()
    vb = [float(x) for x in root.get("viewBox").split()]
    w, h = vb[2], vb[3]
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by scripts/svg2vd.py from {src}. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{w:g}dp" android:height="{h:g}dp"',
        f'    android:viewportWidth="{w:g}" android:viewportHeight="{h:g}">',
    ]
    walk(root, lines)
    lines.append("</vector>")
    open(out, "w").write("\n".join(lines) + "\n")


main()
